export interface ServiceWorkerOptions {
  /** Prefix for this app's cache names, e.g. "myapp" -> "myapp-shell-v1", "myapp-api-v1". */
  cachePrefix: string;
  /**
   * Cache version, folded into the cache names. Change it on every deploy (e.g. pass your build id
   * or git sha) so the new worker's activate handler purges the previous build's now-stale cached
   * chunks — otherwise installed devices keep serving old assets and break after you ship.
   * Default "v1".
   */
  version?: string;
  /** Path prefix that identifies API requests. Default "/api/". */
  apiPrefix?: string;
  /** Path prefixes that must never be cached (sensitive or large). Default auth + files. */
  skipPaths?: string[];
  /** Page served when a navigation fails offline and nothing is cached. Default "/". */
  navigationFallback?: string;
  /**
   * Opt-in web push. `true` adds a `push` handler (JSON payload `{ title, body, url, tag }`) and a
   * `notificationclick` handler. Pass `{ fetchUrl }` as well to support payload-free pushes: when a
   * push arrives with no data, the worker fetches that same-origin URL and shows the JSON it
   * returns. Default off, and then the worker has no push code at all.
   */
  push?: boolean | { fetchUrl?: string };
}

const PUSH_SOURCE = `
const PUSH_FETCH = __PUSH_FETCH__;

function pushMessage(event) {
  if (event.data) {
    try {
      return Promise.resolve(event.data.json());
    } catch (e) {
      return Promise.resolve(null);
    }
  }
  if (!PUSH_FETCH) return Promise.resolve(null);
  try {
    const u = new URL(PUSH_FETCH, self.location.origin);
    if (u.origin !== self.location.origin) return Promise.resolve(null);
    return fetch(u.href, { credentials: "same-origin", cache: "no-store" })
      .then((r) => (r.ok ? r.json() : null))
      .catch(() => null);
  } catch (e) {
    return Promise.resolve(null);
  }
}

self.addEventListener("push", (event) => {
  event.waitUntil(
    pushMessage(event)
      .then((msg) => {
        if (!msg || typeof msg !== "object" || typeof msg.title !== "string" || !msg.title) return;
        const options = { data: { url: typeof msg.url === "string" ? msg.url : null } };
        if (typeof msg.body === "string") options.body = msg.body;
        if (typeof msg.tag === "string") options.tag = msg.tag;
        return self.registration.showNotification(msg.title, options);
      })
      .catch(() => {}),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const scope = self.registration.scope.endsWith("/") ? self.registration.scope : self.registration.scope + "/";
  const raw = event.notification.data && event.notification.data.url;
  let target = null;
  if (typeof raw === "string") {
    target = scope;
    try {
      const u = new URL(raw, scope);
      if (u.origin === self.location.origin) target = u.href;
    } catch (e) {}
  }
  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((wins) => {
        const win = wins.find((c) => c.url.startsWith(scope));
        const open = () => self.clients.openWindow(target || scope);
        if (!win) return open();
        return win
          .focus()
          .then(() => (target && win.navigate ? win.navigate(target) : undefined))
          .catch(open);
      })
      .catch(() => {}),
  );
});
`;

/**
 * Build the source of a secure, network-first service worker as a string. Write the result to a
 * static file your site serves at the root (e.g. `public/sw.js`), then call
 * `registerServiceWorker()` from your app.
 *
 * Strategy: app shell cache-first; navigations network-first with an offline page fallback; API
 * GETs network-first (fresh online, cached only as an offline fallback). Never caches the skip
 * paths, only same-origin 200s, and clears the API cache when the app posts "clear-api-cache".
 */
export function generateServiceWorker(opts: ServiceWorkerOptions): string {
  const {
    cachePrefix,
    version = "v1",
    apiPrefix = "/api/",
    skipPaths = ["/api/auth/", "/api/files/"],
    navigationFallback = "/",
    push = false,
  } = opts;

  if (!cachePrefix) throw new Error("generateServiceWorker: cachePrefix is required");

  const skips = JSON.stringify(skipPaths);
  const pushCode = push
    ? PUSH_SOURCE.replace(
        "__PUSH_FETCH__",
        () => JSON.stringify(typeof push === "object" && push.fetchUrl ? push.fetchUrl : null),
      )
    : "";

  return `// Generated by @baryodev/pwa-kit. Do not edit by hand; regenerate instead.
const OWN = ${JSON.stringify([`${cachePrefix}-shell-`, `${cachePrefix}-api-`])};
const SHELL = ${JSON.stringify(`${cachePrefix}-shell-${version}`)};
const API = ${JSON.stringify(`${cachePrefix}-api-${version}`)};
const API_PREFIX = ${JSON.stringify(apiPrefix)};
const SKIP = ${skips};
const NAV_FALLBACK = ${JSON.stringify(navigationFallback)};

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => OWN.some((p) => k.startsWith(p)) && k !== SHELL && k !== API).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "clear-api-cache") event.waitUntil(caches.delete(API));
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (SKIP.some((p) => url.pathname.startsWith(p))) return;

  if (url.pathname.startsWith(API_PREFIX)) {
    event.respondWith(
      fetch(req)
        .then((resp) => {
          if (resp.ok && resp.type === "basic") {
            const copy = resp.clone();
            event.waitUntil(caches.open(API).then((c) => c.put(req, copy)));
          }
          return resp;
        })
        .catch(() =>
          caches.open(API).then((c) => c.match(req)).then(
            (cached) =>
              cached ||
              new Response(JSON.stringify({ offline: true }), {
                status: 503,
                headers: { "Content-Type": "application/json" },
              }),
          ),
        ),
    );
    return;
  }

  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((resp) => {
          if (resp.ok && resp.type === "basic" && !resp.redirected) {
            const copy = resp.clone();
            event.waitUntil(caches.open(SHELL).then((c) => c.put(req, copy)));
          }
          return resp;
        })
        .catch(() =>
          caches.open(SHELL).then((c) => c.match(req).then((r) => r || c.match(NAV_FALLBACK))),
        ),
    );
    return;
  }

  event.respondWith(
    caches.open(SHELL).then((c) => c.match(req)).then(
      (cached) =>
        cached ||
        fetch(req).then((resp) => {
          if (resp.ok && resp.type === "basic") {
            const copy = resp.clone();
            event.waitUntil(caches.open(SHELL).then((c) => c.put(req, copy)));
          }
          return resp;
        }),
    ),
  );
});
` + pushCode;
}
